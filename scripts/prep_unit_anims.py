"""Ship the baked unit animation sheets (tools/render3d.ts, tools/jobs-anim.json).

Reads assets-src/renders/anim/<id>_<clip>.png + <id>_anim.json, writes public/assets/anim/<id>_<clip>.webp and
src/scenes/unitAnims.ts (cell sizes, frame counts, durations, and `body`: px from the feet to the top of the head in
the idle pose, which the game maps to the unit's on-screen height).
Run: python3 scripts/prep_unit_anims.py
"""
import glob
import json
import os

from PIL import Image

SRC = 'assets-src/renders/anim'
OUT = 'public/assets/anim'
os.makedirs(OUT, exist_ok=True)

# Units are sized by their head bone, not their tallest pixel, so a raised spear, wings or a tall hat do not shrink
# them. HEAD_TO_TOP turns the head joint's height into the top of a chibi head (measured on cn_sword, which has none
# of those). Units without a head bone fall back to the whole model's height.
ref = json.load(open(f'{SRC}/cn_sword_anim.json'))['heights']
HEAD_TO_TOP = ref['top'] / ref['head']

anims = {}
for meta_path in sorted(glob.glob(f'{SRC}/*_anim.json')):
    uid = os.path.basename(meta_path)[: -len('_anim.json')]
    meta = json.load(open(meta_path))
    pad = meta['pad']
    entry = {'pad': pad, 'body': 0, 'clips': {}}
    for clip, c in meta['clips'].items():
        im = Image.open(f'{SRC}/{uid}_{clip}.png')
        im.save(f'{OUT}/{uid}_{clip}.webp', 'WEBP', quality=88, method=6)
        entry['clips'][clip] = {'w': c['w'], 'h': c['h'], 'frames': c['frames'], 'duration': round(c['duration'], 3)}
    h = meta['heights']
    biped = 'idle' in meta['clips']  # the walk-only quadruped's head sits at a different proportion
    entry['body'] = round(h['head'] * HEAD_TO_TOP) if biped and h.get('head') else h['top']
    anims[uid] = entry
    print(uid, entry['body'], {k: (v['w'], v['h']) for k, v in entry['clips'].items()})

with open('src/scenes/unitAnims.ts', 'w') as f:
    f.write('// Generated by scripts/prep_unit_anims.py from the baked sheets in assets-src/renders/anim. Do not edit.\n')
    f.write("export type UnitClip = 'idle' | 'walk' | 'attack';\n")
    f.write('export interface ClipSheet { w: number; h: number; frames: number; duration: number }\n')
    f.write('export interface UnitAnim { pad: number; body: number; clips: Partial<Record<UnitClip, ClipSheet>> }\n')
    f.write('export const UNIT_ANIMS: Record<string, UnitAnim> = ' + json.dumps(anims, indent=2) + ';\n')
